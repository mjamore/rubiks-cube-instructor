// Regenerate the local female narration on macOS; no microphone or network is used.
import {execFileSync} from 'node:child_process';
import {mkdirSync,writeFileSync,mkdtempSync,rmSync,statSync} from 'node:fs';
import {tmpdir} from 'node:os';
import {join} from 'node:path';
import {FACES,LESSONS,explain} from '../src/cube-state.js';
const sentences=[
 'Let’s learn one move at a time.',
 'You did it! All the colors match.',
 'One more turn the same way.',
 ...LESSONS.map(lesson=>lesson.description),
 ...FACES.flatMap(face=>['',"'",'2'].map(suffix=>explain(face+suffix).title)),
 ...FACES.flatMap(face=>['',"'",'2'].map(suffix=>`${face} ${suffix==="'"?'prime':suffix==='2'?'two':''}`.trim()))
];
mkdirSync('public/voice',{recursive:true});
const directory=mkdtempSync(join(tmpdir(),'cubie-voice-'));
const clips={};
try{
 for(const [i,text] of [...new Set(sentences)].entries()){
  const file=`instruction-${String(i+1).padStart(2,'0')}.m4a`,aiff=join(directory,'voice.aiff');
  execFileSync('/usr/bin/say',['-v','Samantha','-r','155','-o',aiff,text]);
  execFileSync('ffmpeg',['-hide_banner','-loglevel','error','-y','-i',aiff,'-codec:a','aac','-b:a','64k',join('public/voice',file)]);
  if(statSync(join('public/voice',file)).size<1000)throw new Error('The speech engine produced no audio. Run with access to the macOS speech service.');
  clips[text]=`/voice/${file}`;
 }
 writeFileSync('src/voice-clips.js',`// Generated by scripts/record-voice.mjs using the macOS Samantha voice.\nexport const VOICE_CLIPS=${JSON.stringify(clips,null,2)};\n`);
 console.log(`Recorded ${Object.keys(clips).length} female voice instructions.`);
}finally{rmSync(directory,{recursive:true,force:true});}
